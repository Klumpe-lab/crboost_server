"""Star conversion around `WarpTools ts_export_particles --2d` (Warp 2.0.0dev40+).

Two directions, both pure (DataFrames in, DataFrames out; the driver does the file I/O):

- **In**: a RELION-5 candidate / particle table (centred Å) → Warp's input table:
  corner-origin `rlnCoordinateX/Y/Z` in unbinned pixels of the volume the Warp settings
  describe, tilt series named `<ts>.tomostar` in `rlnMicrographName`. Every other column
  rides along; Warp copies unknown columns into its output row for row.

- **Out**: Warp's particle table → a RELION-5 particle table that pairs with the tsCtf
  job's per-tilt geometry. Warp's own tomograms star is not used: it describes a virtual
  tomogram at the particle pixel size with RELION-4 projection matrices and a dummy tilt
  series. Instead the tsCtf per-tilt star is reordered into Warp's frame order (the
  tomostar rows), because `rlnTomoVisibleFrames` and the stack slices index those frames.
  Positions are the carried centred-Å coordinates (RELION prefers them over
  rlnCoordinateX/Y/Z), so the per-particle depth defocus uses the real tomogram size,
  pixel size and hand, exactly as for RELION extraction.
"""

from __future__ import annotations

import xml.etree.ElementTree as ET
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd

from services.particles.coords import CENTERED_COLS

TOMOSTAR_SUFFIX = ".tomostar"

COORD_COLS = ["rlnCoordinateX", "rlnCoordinateY", "rlnCoordinateZ"]
ANGLE_COLS = ["rlnAngleRot", "rlnAngleTilt", "rlnAnglePsi"]
ORIGIN_ANGST_COLS = ["rlnOriginXAngst", "rlnOriginYAngst", "rlnOriginZAngst"]
ORIGIN_PIXEL_COLS = ["rlnOriginX", "rlnOriginY", "rlnOriginZ"]
SUBTOMO_ANGLE_COLS = ["rlnTomoSubtomogramRot", "rlnTomoSubtomogramTilt", "rlnTomoSubtomogramPsi"]

# Regenerated by the export, or meaningless for it (image/optics of an earlier extraction).
_DROP_FROM_INPUT = [
    "rlnImageName",
    "rlnCtfImage",
    "rlnTomoVisibleFrames",
    "rlnTomoParticleId",
    "rlnTomoParticleName",
    "rlnOpticsGroup",
    "rlnOpticsGroupName",
    "rlnPixelSize",
    "rlnImagePixelSize",
    *ORIGIN_ANGST_COLS,
]

# RELION 5 builds the projection matrices only when all four are present, else silently
# uses identity; rlnMicrographName is how each frame names its own image.
REQUIRED_TILT_COLS = ["rlnMicrographName", "rlnTomoYTilt", "rlnTomoZRot", "rlnTomoXShiftAngst", "rlnTomoYShiftAngst"]

# Warp writes coordinates with 3 decimals in output pixels; anything beyond this means the
# carried columns no longer belong to the row Warp exported.
_ROW_MATCH_TOLERANCE_ANGST = 0.1


@dataclass(frozen=True)
class WarpVolume:
    """The volume a Warp settings file describes: unbinned pixel size and dimensions."""

    apix: float
    dims: tuple[int, int, int]

    @property
    def centre_angst(self) -> np.ndarray:
        return np.asarray(self.dims, dtype=float) * self.apix / 2.0


@dataclass(frozen=True)
class TsCtfSources:
    """The Warp inputs of one tilt series, found from its tomogram row: the tsCtf job that
    wrote the row's per-tilt star also holds the CTF-fitted XML, its settings copy and the
    in-scope tomostars."""

    job_dir: Path
    tilt_star: Path
    settings: Path
    tomostar: Path
    xml: Path


def read_warp_volume(settings_path: Path) -> WarpVolume:
    """Import/PixelSize and Tomo/Dimensions{X,Y,Z} from a Warp .settings file."""
    root = ET.parse(settings_path).getroot()

    def _param(section: str, name: str) -> float:
        parent = root.find(section)
        if parent is None:
            raise ValueError(f"<{section}> section missing in {settings_path}")
        for p in parent.findall("Param"):
            if p.get("Name") == name:
                value = (p.get("Value") or "").strip()
                if not value:
                    raise ValueError(f"{section}/{name} is blank in {settings_path}")
                return float(value)
        raise ValueError(f"{section}/{name} not found in {settings_path}")

    apix = _param("Import", "PixelSize")
    dims = tuple(int(_param("Tomo", f"Dimensions{a}")) for a in "XYZ")
    if apix <= 0 or min(dims) <= 0:
        raise ValueError(f"Non-positive pixel size or volume dimensions in {settings_path}: {apix}, {dims}")
    return WarpVolume(apix=apix, dims=dims)


def tsctf_sources(tomo_row: pd.Series, settings_name: str, tomostar_dir_name: str) -> TsCtfSources:
    """Locate the tsCtf job behind a tomogram row via its rlnTomoTiltSeriesStarFile
    (`<tsCtf job>/tilt_series/<ts>.star`). Raises naming every missing piece."""
    ts = str(tomo_row["rlnTomoName"])
    raw = str(tomo_row.get("rlnTomoTiltSeriesStarFile", "") or "")
    if not raw:
        raise ValueError(f"{ts}: tomogram row has no rlnTomoTiltSeriesStarFile")
    tilt_star = Path(raw)
    if not tilt_star.is_absolute():
        raise ValueError(
            f"{ts}: rlnTomoTiltSeriesStarFile is relative ({raw}); expected the absolute path tsReconstruct writes"
        )
    job_dir = tilt_star.parent.parent
    sources = TsCtfSources(
        job_dir=job_dir,
        tilt_star=tilt_star,
        settings=job_dir / settings_name,
        tomostar=job_dir / tomostar_dir_name / f"{ts}{TOMOSTAR_SUFFIX}",
        xml=job_dir / "warp_tiltseries" / f"{ts}.xml",
    )
    missing = [str(p) for p in (sources.tilt_star, sources.settings, sources.tomostar, sources.xml) if not p.exists()]
    if missing:
        raise FileNotFoundError(
            f"{ts}: the tilt series' tsCtf job ({job_dir}) lacks {missing}. Warp export needs the tsCtf job "
            f"that wrote this tomogram's per-tilt star (imported tomograms have none)."
        )
    return sources


def check_volume_agrees(tomo_row: pd.Series, volume: WarpVolume) -> None:
    """The tomogram row and the Warp settings must describe the same volume: Warp places the
    particles in its frame, RELION computes the depth defocus in the row's."""
    ts = str(tomo_row["rlnTomoName"])
    row_apix = float(tomo_row["rlnTomoTiltSeriesPixelSize"])
    if abs(row_apix - volume.apix) > 1e-3 * volume.apix:
        raise ValueError(
            f"{ts}: tilt-series pixel size {row_apix} Å in tomograms.star, {volume.apix} Å in Warp settings"
        )
    row_dims = [round(float(tomo_row[f"rlnTomoSize{a}"])) for a in "XYZ"]
    if any(abs(r - w) > 1 for r, w in zip(row_dims, volume.dims, strict=True)):
        raise ValueError(
            f"{ts}: tomogram size {row_dims} px in tomograms.star, {list(volume.dims)} px in Warp settings"
        )


def read_tomostar_movies(tomostar_df: pd.DataFrame) -> list[str]:
    """Movie names in tomostar row order = Warp's tilt index order."""
    if "wrpMovieName" not in tomostar_df.columns:
        raise ValueError(f"tomostar has no _wrpMovieName column (columns: {list(tomostar_df.columns)})")
    return [str(m) for m in tomostar_df["wrpMovieName"]]


def warp_input_particles(particles: pd.DataFrame, ts_name: str, volume: WarpVolume) -> pd.DataFrame:
    """One tilt series' picks as Warp's input table.

    Origins in Å are folded into the centred coordinates first (RELION's position is
    coordinate − origin), so Warp and the carried centred columns name the same point.
    """
    if particles.empty:
        raise ValueError(f"{ts_name}: no particles to export")
    present_subtomo = [c for c in SUBTOMO_ANGLE_COLS if c in particles.columns]
    if present_subtomo:
        raise ValueError(
            f"{ts_name}: input carries {present_subtomo} (a RELION extraction output). Their rotation would "
            f"apply on top of rlnAngle* downstream; export from the candidates instead."
        )
    present_px_origin = [c for c in ORIGIN_PIXEL_COLS if c in particles.columns]
    if present_px_origin:
        raise ValueError(f"{ts_name}: pixel origins {present_px_origin} are not supported; RELION 5 writes them in Å")
    missing = [c for c in CENTERED_COLS + ANGLE_COLS if c not in particles.columns]
    if missing:
        raise ValueError(f"{ts_name}: input particles lack {missing}")

    df = particles.copy().reset_index(drop=True)
    centred = df[CENTERED_COLS].to_numpy(dtype=float)
    origin_cols = [c for c in ORIGIN_ANGST_COLS if c in df.columns]
    if origin_cols:
        if len(origin_cols) != 3:
            raise ValueError(f"{ts_name}: partial origin columns {origin_cols}")
        centred = centred - df[ORIGIN_ANGST_COLS].to_numpy(dtype=float)
    df[CENTERED_COLS] = centred

    df = df.drop(columns=[c for c in _DROP_FROM_INPUT if c in df.columns])
    corner_px = (centred + volume.centre_angst) / volume.apix
    for i, col in enumerate(COORD_COLS):
        df[col] = corner_px[:, i]
    df["rlnMicrographName"] = f"{ts_name}{TOMOSTAR_SUFFIX}"
    return df


def tilt_table_in_warp_order(tilt_df: pd.DataFrame, movies: list[str], ts_name: str) -> pd.DataFrame:
    """The tsCtf per-tilt rows, one per tomostar movie, in tomostar order.

    Matched by movie file name (stem as a fallback). Rows without a tomostar movie are
    tilts ts_import left out; Warp never sees them, so they are dropped."""
    missing_cols = [c for c in [*REQUIRED_TILT_COLS, "rlnMicrographMovieName"] if c not in tilt_df.columns]
    if missing_cols:
        raise ValueError(f"{ts_name}: per-tilt star lacks {missing_cols}")

    names = [Path(str(m)).name for m in tilt_df["rlnMicrographMovieName"]]
    by_name: dict[str, int] = {}
    by_stem: dict[str, int] = {}
    for i, name in enumerate(names):
        if name in by_name:
            raise ValueError(f"{ts_name}: movie {name} appears twice in the per-tilt star")
        by_name[name] = i
        by_stem[Path(name).stem] = i

    order: list[int] = []
    unmatched: list[str] = []
    for movie in movies:
        name = Path(movie).name
        idx = by_name.get(name, by_stem.get(Path(name).stem))
        if idx is None:
            unmatched.append(name)
        else:
            order.append(idx)
    if unmatched:
        raise ValueError(
            f"{ts_name}: {len(unmatched)} tomostar movie(s) have no row in the per-tilt star: {unmatched[:5]}"
        )
    if len(set(order)) != len(order):
        raise ValueError(f"{ts_name}: two tomostar movies map to one per-tilt row")
    return tilt_df.iloc[order].reset_index(drop=True)


def check_warp_optics(warp_optics: pd.DataFrame, tomo_row: pd.Series, *, box: int, premultiplied: bool) -> float:
    """Warp's optics row must agree with the tomogram's CTF constants and our request.
    Returns Warp's output pixel size."""
    ts = str(tomo_row["rlnTomoName"])
    if len(warp_optics) != 1:
        raise ValueError(f"{ts}: expected one optics row from Warp, got {len(warp_optics)}")
    row = warp_optics.iloc[0]
    for col in ("rlnVoltage", "rlnSphericalAberration", "rlnAmplitudeContrast"):
        if abs(float(row[col]) - float(tomo_row[col])) > 1e-3 * max(1.0, abs(float(tomo_row[col]))):
            raise ValueError(f"{ts}: {col} is {row[col]} in Warp's export, {tomo_row[col]} in tomograms.star")
    if int(row["rlnImageSize"]) != box:
        raise ValueError(f"{ts}: Warp wrote box {row['rlnImageSize']}, requested {box}")
    if int(row["rlnCtfDataAreCtfPremultiplied"]) != int(premultiplied):
        raise ValueError(
            f"{ts}: Warp's premultiplied flag is {row['rlnCtfDataAreCtfPremultiplied']}, expected {int(premultiplied)}"
        )
    return float(row["rlnImagePixelSize"])


def relion_particles_from_warp(
    warp_particles: pd.DataFrame,
    ts_name: str,
    volume: WarpVolume,
    *,
    output_apix: float,
    n_frames: int,
    image_dir: Path,
) -> pd.DataFrame:
    """Warp's particle rows for one tilt series → RELION-5 rows.

    Keeps Warp's rlnImageName (re-pointed into `image_dir`), rlnTomoVisibleFrames, ids,
    angles; restores the tilt-series name; drops Warp's output-pixel rlnCoordinateX/Y/Z in
    favour of the carried centred Å coordinates; writes zero origins explicitly. Raises when
    a carried row no longer matches Warp's position."""
    if warp_particles.empty:
        return warp_particles.copy()
    missing = [
        c for c in CENTERED_COLS + COORD_COLS + ["rlnImageName", "rlnTomoVisibleFrames"] if c not in warp_particles
    ]
    if missing:
        raise ValueError(f"{ts_name}: Warp's particle table lacks {missing} (centred columns need Warp 2.0.0dev38+)")

    df = warp_particles.copy().reset_index(drop=True)
    names = set(df["rlnTomoName"].astype(str))
    if names != {f"{ts_name}{TOMOSTAR_SUFFIX}"}:
        raise ValueError(f"{ts_name}: Warp's particle table names tilt series {sorted(names)}")
    df["rlnTomoName"] = ts_name

    lengths = {len(str(v).strip("[]").split(",")) for v in df["rlnTomoVisibleFrames"]}
    if lengths != {n_frames}:
        raise ValueError(
            f"{ts_name}: rlnTomoVisibleFrames lengths {sorted(lengths)}, the per-tilt star has {n_frames} frames"
        )

    expected = df[CENTERED_COLS].to_numpy(dtype=float) + volume.centre_angst
    exported = df[COORD_COLS].to_numpy(dtype=float) * output_apix
    worst = float(np.abs(expected - exported).max())
    if worst > _ROW_MATCH_TOLERANCE_ANGST:
        raise ValueError(
            f"{ts_name}: Warp's positions differ from the carried centred coordinates by up to {worst:.2f} Å; "
            f"the carried columns are not aligned with Warp's rows"
        )

    df["rlnImageName"] = [str(image_dir / Path(str(p)).name) for p in df["rlnImageName"]]
    df = df.drop(columns=COORD_COLS + [c for c in ("rlnMicrographName",) if c in df.columns])
    for col in ORIGIN_ANGST_COLS:
        df[col] = 0.0
    return df


def optics_key(tomo_row: pd.Series) -> tuple:
    """Particles of tomograms that share these constants share an optics group."""
    return (
        str(tomo_row.get("rlnOpticsGroupName", "") or ""),
        float(tomo_row["rlnVoltage"]),
        float(tomo_row["rlnSphericalAberration"]),
        float(tomo_row["rlnAmplitudeContrast"]),
        float(tomo_row["rlnTomoTiltSeriesPixelSize"]),
    )


def optics_table(keys: list[tuple], *, output_apix: float, box: int, premultiplied: bool) -> pd.DataFrame:
    """One optics row per key, numbered from 1 in the given order. Only groups that hold
    particles are passed in, so no group is empty."""
    rows = []
    for i, (name, voltage, cs, q0, ts_apix) in enumerate(keys, 1):
        rows.append(
            {
                "rlnOpticsGroup": i,
                "rlnOpticsGroupName": name or f"opticsGroup{i}",
                "rlnSphericalAberration": cs,
                "rlnVoltage": voltage,
                "rlnAmplitudeContrast": q0,
                "rlnTomoTiltSeriesPixelSize": ts_apix,
                "rlnCtfDataAreCtfPremultiplied": int(premultiplied),
                "rlnImageDimensionality": 2,
                "rlnTomoSubtomogramBinning": output_apix / ts_apix,
                "rlnImagePixelSize": output_apix,
                "rlnImageSize": box,
            }
        )
    return pd.DataFrame(rows)
